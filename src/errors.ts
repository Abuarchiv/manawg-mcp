export class ManaWgError extends Error {
  readonly code: string;
  readonly status: number;
  readonly details?: string;
  readonly retryAfterSeconds?: number;

  constructor(
    code: string,
    status: number,
    options: { details?: string; retryAfterSeconds?: number } = {},
  ) {
    super(`ManaWG request failed: ${code}`);
    this.name = 'ManaWgError';
    this.code = code;
    this.status = status;
    if (options.details !== undefined) {
      this.details = options.details;
    }
    if (options.retryAfterSeconds !== undefined) {
      this.retryAfterSeconds = options.retryAfterSeconds;
    }
  }
}

export function isSafeCode(value: unknown): value is string {
  return typeof value === 'string' && SAFE_UPSTREAM_CODES.has(value);
}

/** Model-facing text for any failure: allowlisted code, details and retry hint only. */
export function describeError(error: unknown): string {
  if (!(error instanceof ManaWgError)) {
    return SAFE_ERROR_MESSAGE;
  }
  let message = `${SAFE_ERROR_MESSAGE}: ${error.code}`;
  if (error.details) {
    message = `${message} (${error.details})`;
  }
  if (error.retryAfterSeconds !== undefined) {
    message = `${message} retry_after_s=${error.retryAfterSeconds}`;
  }
  return message;
}
